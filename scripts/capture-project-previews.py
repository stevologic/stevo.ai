#!/usr/bin/env python3
"""Capture a 1280x800 screenshot of every project's live site for its card.

Writes public/project-previews/<slug>.webp (downscaled to 640x400) and
data/project-previews.generated.json. A site that fails to load keeps its
previous image and entry. Requires: pip install playwright pillow &&
playwright install chromium.  Usage: python3 scripts/capture-project-previews.py
"""
import io, json, sys, datetime, pathlib
from PIL import Image
from playwright.sync_api import sync_playwright

root = pathlib.Path(__file__).resolve().parent.parent
out_dir = root / "public" / "project-previews"
data_file = root / "data" / "project-previews.generated.json"
# Cards whose screenshot should come from a different page than siteUrl.
CAPTURE_URL = {"winter-hunt": "https://stevologic.github.io/winter-hunt-tracker/"}


def projects():
    curated = json.loads((root / "content/projects.json").read_text())
    discovered = json.loads((root / "data/discovered.generated.json").read_text()).get("projects", [])
    repos = {p["repo"].lower() for p in curated if p.get("repo")}
    return curated + [p for p in discovered if p.get("repo", "").lower() not in repos]


def main():
    out_dir.mkdir(parents=True, exist_ok=True)
    previous = json.loads(data_file.read_text()) if data_file.exists() else {}
    previews = previous.get("previews", {})
    failed = []
    with sync_playwright() as p:
        browser = p.chromium.launch()
        for project in projects():
            slug, url = project["slug"], CAPTURE_URL.get(project["slug"], project["siteUrl"])
            page = browser.new_page(viewport={"width": 1280, "height": 800})
            try:
                response = page.goto(url, wait_until="load", timeout=45000)
                if response is not None and response.status >= 400:
                    raise RuntimeError(f"HTTP {response.status}")
                page.wait_for_timeout(2500)
                png = page.screenshot(type="png")
                img = Image.open(io.BytesIO(png)).convert("RGB").resize((640, 400), Image.LANCZOS)
                img.save(out_dir / f"{slug}.webp", "WEBP", quality=72, method=6)
                previews[slug] = {
                    "src": f"/project-previews/{slug}.webp",
                    "alt": f"Screenshot of {project['name']}'s live site",
                    "source": url,
                    "capturedAt": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
                }
                print(f"ok   {slug} {url}")
            except Exception as error:  # keep the last committed image
                failed.append(slug)
                print(f"FAIL {slug} {url}: {error}", file=sys.stderr)
            finally:
                page.close()
        browser.close()
    data_file.write_text(json.dumps({
        "schemaVersion": 1,
        "note": "Generated by scripts/capture-project-previews.py. Do not edit by hand.",
        "previews": dict(sorted(previews.items())),
    }, indent=2) + "\n")
    if failed:
        print("failed: " + ", ".join(failed), file=sys.stderr)


if __name__ == "__main__":
    main()
